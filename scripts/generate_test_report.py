import io
import json
import os
import platform
import sqlite3
import subprocess
import sys
import unittest
import xml.etree.ElementTree as ElementTree
from datetime import datetime, timezone
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SUREFIRE_DIR = ROOT / "target" / "surefire-reports"
OUTPUT_DIR = ROOT / "reports" / "tests"


def java_suites():
    suites = []
    for path in sorted(SUREFIRE_DIR.glob("TEST-*.xml")):
        suite = ElementTree.parse(path).getroot()
        failed = int(suite.get("failures", "0")) + int(suite.get("errors", "0"))
        skipped = int(suite.get("skipped", "0"))
        total = int(suite.get("tests", "0"))
        suites.append({
            "suite": suite.get("name").removeprefix("io.github.juanmafx.p3exercises."),
            "tests": total,
            "passed": total - failed - skipped,
            "failed": failed,
            "skipped": skipped,
        })
    if not suites:
        raise SystemExit("no Surefire reports found")
    return suites


def schema_suite():
    loader = unittest.TestLoader()
    tests = loader.discover(str(ROOT / "db" / "tests"), top_level_dir=str(ROOT / "db" / "tests"))
    result = unittest.TextTestRunner(stream=io.StringIO(), verbosity=0).run(tests)
    failed = len(result.failures) + len(result.errors)
    skipped = len(result.skipped)
    return {
        "suite": "db.tests.test_schema",
        "tests": result.testsRun,
        "passed": result.testsRun - failed - skipped,
        "failed": failed,
        "skipped": skipped,
    }


def parent_commit():
    completed = subprocess.run(
        ["git", "rev-parse", "--short", "HEAD"], cwd=ROOT, capture_output=True, text=True, check=True
    )
    return completed.stdout.strip()


def main():
    suites = java_suites() + [schema_suite()]
    totals = {key: sum(suite[key] for suite in suites) for key in ("tests", "passed", "failed", "skipped")}
    report = {
        "generated_at_utc": datetime.now(timezone.utc).strftime("%Y-%m-%dT%H:%M:%SZ"),
        "parent_commit": parent_commit(),
        "command": "./scripts/run-tests.sh",
        "environment": {
            "java": os.environ.get("JAVA_RUNTIME", "unknown"),
            "maven": os.environ.get("MAVEN_RUNTIME", "unknown"),
            "python": platform.python_version(),
            "sqlite": sqlite3.sqlite_version,
        },
        "totals": totals,
        "suites": suites,
    }
    OUTPUT_DIR.mkdir(parents=True, exist_ok=True)
    (OUTPUT_DIR / "test-report.json").write_text(json.dumps(report, indent=2) + "\n", encoding="utf-8")
    lines = [
        "# Test Report",
        "",
        "Generated by `./scripts/run-tests.sh` from real Surefire and unittest results.",
        "",
        f"- Generated at (UTC): {report['generated_at_utc']}",
        f"- Parent commit of the tested working tree: `{report['parent_commit']}`",
        f"- Java: {report['environment']['java']}",
        f"- Maven: {report['environment']['maven']}",
        f"- Python: {report['environment']['python']}",
        f"- SQLite: {report['environment']['sqlite']}",
        "",
        f"**Totals: {totals['tests']} tests, {totals['passed']} passed, "
        f"{totals['failed']} failed, {totals['skipped']} skipped.**",
        "",
        "| Suite | Tests | Passed | Failed | Skipped |",
        "| --- | ---: | ---: | ---: | ---: |",
    ]
    lines += [
        f"| `{s['suite']}` | {s['tests']} | {s['passed']} | {s['failed']} | {s['skipped']} |" for s in suites
    ]
    (OUTPUT_DIR / "test-report.md").write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"{totals['tests']} tests, {totals['passed']} passed, {totals['failed']} failed, {totals['skipped']} skipped")
    return 1 if totals["failed"] else 0


if __name__ == "__main__":
    sys.exit(main())
